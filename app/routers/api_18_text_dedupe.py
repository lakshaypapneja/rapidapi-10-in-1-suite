import re
from fastapi import APIRouter
from pydantic import BaseModel, Field

router = APIRouter(
    prefix="/api/v1/deduplicate-text",
    tags=["18. LLM Output Loop & Repetition Deduplicator"],
)


class DedupeRequest(BaseModel):
    text: str = Field(
        default="The API is ready. The API is ready. Please proceed with testing. Please proceed with testing. Thank you!",
        description="Repetitive or looping text generated by an LLM to clean up.",
    )
    window_unit: str = Field(
        default="sentence",
        description="Deduplication granularity: 'sentence', 'line', or 'paragraph'.",
    )


class DedupeResponse(BaseModel):
    deduplicated_text: str
    original_units_count: int
    cleaned_units_count: int
    duplicates_removed: int


@router.post(
    "/dedupe",
    response_model=DedupeResponse,
    summary="Remove repetitive sentence and paragraph loops often generated by local or small LLMs",
)
async def deduplicate_output(payload: DedupeRequest):
    text = payload.text.strip()
    if not text:
        return DedupeResponse(
            deduplicated_text="",
            original_units_count=0,
            cleaned_units_count=0,
            duplicates_removed=0,
        )

    if payload.window_unit == "line":
        units = text.split("\n")
        join_char = "\n"
    elif payload.window_unit == "paragraph":
        units = text.split("\n\n")
        join_char = "\n\n"
    else:  # sentence
        units = [s.strip() for s in re.split(r"(?<=[.!?])\s+", text) if s.strip()]
        join_char = " "

    seen: set[str] = set()
    cleaned: list[str] = []

    for u in units:
        norm = re.sub(r"\W+", "", u).lower()
        if norm and norm not in seen:
            seen.add(norm)
            cleaned.append(u)

    deduped = join_char.join(cleaned)

    return DedupeResponse(
        deduplicated_text=deduped,
        original_units_count=len(units),
        cleaned_units_count=len(cleaned),
        duplicates_removed=len(units) - len(cleaned),
    )
